with open('src/data/translations.ts', 'r', encoding='utf-8') as f:
    content = f.read()

languages = ["English", "தமிழ்", "हिन्दी", "ಕನ್ನಡ", "मराठी", "മലയാളം", "తెలుగు"]

for lang in languages:
    marker = f'"{lang}": {{'
    pos = content.find(marker)
    if pos == -1:
        print(f"Error: Could not find language block for {lang}")
        sys.exit(1)
    
    # We will insert new key-values right after `"{lang}": {\n`
    insert_pos = pos + len(marker) + 1 # after newline
    
    lines_to_add = []
    for key, lang_map in new_translations.items():
        # Check if already present in this language section
        # Find the end of this language dictionary (next language or end of object)
        val = lang_map.get(lang, lang_map["English"])
        # Format properly as JSON string
        val_escaped = json.dumps(val, ensure_ascii=False)
        lines_to_add.append(f'    "{key}": {val_escaped},')
    
    insert_str = "\n".join(lines_to_add) + "\n"
    content = content[:insert_pos] + insert_str + content[insert_pos:]
    print(f"Added {len(lines_to_add)} keys to {lang}")

with open('src/data/translations.ts', 'w', encoding='utf-8') as f:
    f.write(content)

print("Successfully updated src/data/translations.ts!")
