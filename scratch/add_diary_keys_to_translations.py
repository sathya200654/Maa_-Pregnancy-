for lang in languages:
    # Look for the language dictionary block
    pattern = rf'("{re.escape(lang)}":\s*\{{)'
    m = re.search(pattern, code)
    if not m:
        print(f"Could not find language block for {lang}!")
        continue
    
    entries = []
    for k, val_map in DIARY_KEYS.items():
        v = val_map.get(lang, val_map["English"]).replace('"', '\\"')
        entries.append(f'    {k}: "{v}",')
    
    block_insert = "\n" + "\n".join(entries)
    code = code[:m.end()] + block_insert + code[m.end():]
    print(f"Added {len(entries)} keys to {lang}")

with open(trans_file, "w", encoding="utf-8") as f:
    f.write(code)

