/**
 * Localize category name
 */
export function getLocalizedCategory(category: string, lang: SupportedLanguage): string {
  if (lang === "English") return category;
  const match = CATEGORY_TRANSLATIONS[category];
  if (match && match[lang]) {
    return match[lang];
  }
  return category;
}

/**
 * Localize topic term
 */
export function getLocalizedTopic(topic: string, lang: SupportedLanguage): string {
  if (lang === "English") return topic;
  const clean = topic.trim().toLowerCase();
  for (const [key, map] of Object.entries(TOPIC_TERMS)) {
    if (clean === key.toLowerCase() || clean.includes(key.toLowerCase())) {
      return map[lang] || topic;
    }
  }
  return topic;
}

